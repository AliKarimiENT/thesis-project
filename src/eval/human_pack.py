"""
Create human evaluation pack (XLSX) for rating generated questions.
"""

import argparse
import sys
import os
import random
from typing import List, Dict

# Add parent directory to path
sys.path.append(os.path.dirname(os.path.dirname(os.path.dirname(__file__))))

from src.utils.io_utils import load_jsonl, ensure_dir
from src.utils.seed import set_seed
import pandas as pd


def create_human_eval_pack(
    dataset_path: str,
    predA_path: str,
    predB_path: str,
    output_path: str,
    n_samples: int = 120,
    seed: int = 314
):
    """
    Create human evaluation pack with randomized A/B systems.
    
    Args:
        dataset_path: Path to dataset JSONL
        predA_path: Path to system A predictions
        predB_path: Path to system B predictions
        output_path: Output XLSX path
        n_samples: Number of samples to include
        seed: Random seed for sampling and shuffling
    """
    set_seed(seed)
    
    print(f"Loading predictions...")
    predA = load_jsonl(predA_path)
    predB = load_jsonl(predB_path)
    
    # Create ID mapping
    predA_dict = {p['id']: p for p in predA}
    predB_dict = {p['id']: p for p in predB}
    
    # Find common IDs
    common_ids = set(predA_dict.keys()) & set(predB_dict.keys())
    print(f"Found {len(common_ids)} common samples")
    
    # Sample n items
    if len(common_ids) < n_samples:
        print(f"Warning: Only {len(common_ids)} samples available, using all")
        sampled_ids = list(common_ids)
    else:
        sampled_ids = random.sample(list(common_ids), n_samples)
    
    # Create evaluation data
    eval_data = []
    
    for sample_idx, sample_id in enumerate(sampled_ids):
        itemA = predA_dict[sample_id]
        itemB = predB_dict[sample_id]
        
        # Randomize A/B order
        if random.random() < 0.5:
            system_order = ['A', 'B']
            question_order = [itemA['pred_question'], itemB['pred_question']]
            system_names = ['baseline', 'controlled']
        else:
            system_order = ['B', 'A']
            question_order = [itemB['pred_question'], itemA['pred_question']]
            system_names = ['controlled', 'baseline']
        
        eval_data.append({
            'item_id': sample_idx + 1,
            'sample_id': sample_id,
            'context': itemA['context'],
            'answer': itemA['answer'],
            'ref_question': itemA['ref_question'],
            'question_A': question_order[0],
            'question_B': question_order[1],
            'system_A': system_names[0],
            'system_B': system_names[1],
            # Rating columns (to be filled by raters)
            'fluency_A': '',
            'relevance_A': '',
            'answerability_A': '',
            'edu_value_A': '',
            'perceived_diff_A': '',
            'fluency_B': '',
            'relevance_B': '',
            'answerability_B': '',
            'edu_value_B': '',
            'perceived_diff_B': '',
            'notes': ''
        })
    
    # Create instructions sheet
    instructions = """
HUMAN EVALUATION INSTRUCTIONS

Task: Rate the quality of generated questions for reading comprehension.

For each item, you will see:
- Context: A passage of text
- Answer: A specific answer span from the context
- Reference Question: A human-written question
- Question A: Generated by System A
- Question B: Generated by System B

Rate BOTH Question A and Question B on the following dimensions (1-5 scale):

1. FLUENCY (grammatical correctness and naturalness)
   1 = Completely ungrammatical or incomprehensible
   2 = Major grammatical errors
   3 = Minor grammatical errors but understandable
   4 = Mostly fluent with very minor issues
   5 = Perfect grammar and natural phrasing

2. RELEVANCE (how well the question relates to context and answer)
   1 = Completely unrelated
   2 = Weakly related
   3 = Somewhat related
   4 = Mostly relevant
   5 = Perfectly relevant

3. ANSWERABILITY (can the question be answered from the context?)
   1 = Cannot be answered at all
   2 = Difficult to answer; unclear
   3 = Somewhat answerable
   4 = Mostly answerable
   5 = Clearly answerable with the given answer

4. EDUCATIONAL VALUE (how useful for learning/comprehension assessment?)
   1 = No educational value
   2 = Low value
   3 = Moderate value
   4 = Good value
   5 = Excellent educational value

5. PERCEIVED DIFFICULTY (how hard is the question?)
   1 = Very easy
   2 = Easy
   3 = Medium difficulty
   4 = Hard
   5 = Very hard

Notes:
- System identities (A/B) are randomized and blinded
- Compare questions to the reference when helpful
- Use the "notes" column for any additional comments

Thank you for your participation!
    """
    
    # Create Excel file with two sheets
    ensure_dir(os.path.dirname(output_path))
    
    with pd.ExcelWriter(output_path, engine='openpyxl') as writer:
        # Instructions sheet
        instructions_df = pd.DataFrame({'Instructions': [instructions]})
        instructions_df.to_excel(writer, sheet_name='Instructions', index=False)
        
        # Evaluation data sheet
        eval_df = pd.DataFrame(eval_data)
        eval_df.to_excel(writer, sheet_name='Evaluation', index=False)
    
    print(f"\n✓ Saved human evaluation pack to {output_path}")
    print(f"  Number of items: {len(eval_data)}")
    print(f"  Columns: {len(eval_df.columns)}")
    
    # Print summary
    print("\n" + "="*50)
    print("HUMAN EVALUATION PACK CREATED")
    print("="*50)
    print(f"Total items: {len(eval_data)}")
    print(f"System A = baseline in {sum(1 for e in eval_data if e['system_A'] == 'baseline')} items")
    print(f"System B = baseline in {sum(1 for e in eval_data if e['system_B'] == 'baseline')} items")
    print("\nRating dimensions:")
    print("  - Fluency (1-5)")
    print("  - Relevance (1-5)")
    print("  - Answerability (1-5)")
    print("  - Educational Value (1-5)")
    print("  - Perceived Difficulty (1-5)")
    print("="*50)


def main():
    parser = argparse.ArgumentParser(description="Create human evaluation pack")
    parser.add_argument(
        "--dataset",
        type=str,
        required=True,
        help="Path to dataset JSONL"
    )
    parser.add_argument(
        "--predA",
        type=str,
        required=True,
        help="Path to system A predictions"
    )
    parser.add_argument(
        "--predB",
        type=str,
        required=True,
        help="Path to system B predictions"
    )
    parser.add_argument(
        "--out",
        type=str,
        required=True,
        help="Output XLSX path"
    )
    parser.add_argument(
        "--n",
        type=int,
        default=120,
        help="Number of samples to include"
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=314,
        help="Random seed"
    )
    
    args = parser.parse_args()
    
    create_human_eval_pack(
        dataset_path=args.dataset,
        predA_path=args.predA,
        predB_path=args.predB,
        output_path=args.out,
        n_samples=args.n,
        seed=args.seed
    )


if __name__ == "__main__":
    main()

